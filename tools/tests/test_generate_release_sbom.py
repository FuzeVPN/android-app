def varint(value):
    result = bytearray()
    while value >= 128:
        result.append((value & 127) | 128)
        value >>= 7
    result.append(value)
    return bytes(result)


def elf(go_version="go1.26.9", module_version="v0.0.0-20261006164505-2631ce99a06f", extra=""):
    version = go_version.encode()
    modules = ("path\tgolang.zx2c4.com/wireguard/android\n"
        "mod\tgolang.zx2c4.com/wireguard/android\t(devel)\t\n"
        f"dep\tgolang.zx2c4.com/wireguard\t{module_version}\th1:fixture\n"
        "build\tGOOS=android\n"
        "build\tGOARCH=arm64\n"
        "build\tCGO_LDFLAGS=/private/workstation/linker/path\n" + extra).encode()
    modules = b"x" * 16 + modules + b"y" * 16
    header = b"\xff Go buildinf:" + bytes([8, 2]) + bytes(16)
    return b"\x7fELF" + bytes(60) + header + varint(len(version)) + version + varint(len(modules)) + modules


def zipped(entries):
    output = io.BytesIO()
    with zipfile.ZipFile(output, "w") as archive:
        for name, data in sorted(entries.items()):
            info = zipfile.ZipInfo(name, date_time=(2026, 10, 19, 0, 0, 0))
            archive.writestr(info, data)
    return output.getvalue()


def annotation(item):
    return json.loads(item["annotations"][0]["comment"])


