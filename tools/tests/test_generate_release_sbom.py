    def write(self, path, value):
        target = self.root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(value if isinstance(value, bytes) else value.encode())

    def generate(self, **kwargs):
        if kwargs.get("aab") is not None:
            kwargs.setdefault("binary_sha256", sbom.digest(self.binary.read_bytes()))
        return sbom.generate(self.root, created=CREATED, **kwargs)

    def test_compile_and_runtime_versions_are_preserved_separately(self):
        result = self.generate()
        packages = [p for p in result["packages"] if p["name"] == "androidx.core:core-ktx"]
        self.assertEqual({"1.16.0", "1.17.0"}, {p["versionInfo"] for p in packages})
        for p in packages:
            self.assertEqual(["releaseCompileClasspath"] if p["versionInfo"] == "1.16.0" else ["releaseRuntimeClasspath"], annotation(p)["configurations"])
            self.assertEqual("not-established", annotation(p)["binaryPresenceAfterR8"])

    def test_two_annotation_versions_are_not_collapsed(self):
        packages = [p for p in self.generate()["packages"] if p["name"] == "androidx.annotation:annotation"]
        self.assertEqual({"1.9.1", "1.10.0"}, {p["versionInfo"] for p in packages})
        self.assertEqual(2, len({p["SPDXID"] for p in packages}))

