"""Google SDK notices stay reproducible and fresh (A17-supply-chain-05, tooling part)."""
import contextlib
import hashlib
import importlib.util
import io
import json
from pathlib import Path
import tempfile
import unittest
import zipfile

SPEC = importlib.util.spec_from_file_location("google_sdk_notices", Path(__file__).parents[1] / "generate_google_sdk_notices.py")
notices = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(notices)


def aar(texts):
    body, index = b"", {}
    for name, text in texts.items():
        data = text.encode("utf-8")
        index[name] = {"start": len(body), "length": len(data)}
        body += data + b"\n"
    output = io.BytesIO()
    with zipfile.ZipFile(output, "w") as archive:
        archive.writestr("third_party_licenses.json", json.dumps(index))
        archive.writestr("third_party_licenses.txt", body)
        archive.writestr("classes.jar", b"fixture")
    return output.getvalue()


class GoogleSdkNoticeTests(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name) / "repo"
        self.cache = Path(temporary.name) / "cache"
        self.artifacts = {
            "com.android.billingclient:billing:9.1.0": aar({"Protocol Buffers": "BSD 'quoted' $notice\x0c\nline", "JSR 305": "BSD JSR"}),
            "com.google.android.gms:play-services-base:18.5.0": aar({"JSR 305": "BSD JSR"}),
        }
        self.write_lock(list(self.artifacts) + ["com.google.guava:listenablefuture:1.0", "androidx.core:core:1.0"])
        jar = self.cache / "com.google.guava/listenablefuture/1.0/0000/listenablefuture-1.0.jar"
        jar.parent.mkdir(parents=True)
        jar.write_bytes(b"jar")
        self.publish()

    def write_lock(self, coordinates):
        lock = self.root / notices.LOCK
        lock.parent.mkdir(parents=True, exist_ok=True)
        lock.write_text("".join(f"{c}=releaseRuntimeClasspath,debugRuntimeClasspath\n" for c in coordinates)
                        + "com.google.test:only-debug:1=debugRuntimeClasspath\nempty=\n", encoding="utf-8")

    def publish(self, *, verified=None):
        components = []
        for coordinate, data in self.artifacts.items():
            group, name, version = coordinate.split(":")
            path = self.cache / group / name / version / "0000" / f"{name}-{version}.aar"
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
            digest = (verified or {}).get(coordinate, hashlib.sha256(data).hexdigest())
            components.append(f'<component group="{group}" name="{name}" version="{version}"><artifact name="{name}-{version}.aar">'
                              f'<sha256 value="{digest}" origin="Generated by Gradle"/></artifact></component>')
        path = self.root / notices.VERIFICATION
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text('<verification-metadata xmlns="https://schema.gradle.org/dependency-verification"><components>'
                        + "".join(components) + "</components></verification-metadata>", encoding="utf-8")

    def run_tool(self, *arguments):
        with contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()):
            return notices.main(["--root", str(self.root), "--module-cache", str(self.cache), *arguments])

    def test_notices_are_grouped_verified_and_reproduced_exactly(self):
        self.assertEqual(0, self.run_tool())
        content = (self.root / notices.OUTPUT).read_text(encoding="utf-8")
        self.assertEqual(1, content.count("r'''BSD JSR'''"))  # Identical texts are grouped once.
        self.assertIn("<String>['JSR 305'],", content)
        self.assertIn(hashlib.sha256("BSD 'quoted' $notice\x0c\nline".encode()).hexdigest(), content)
        self.assertIn("'\\x0C'", content)
        self.assertIn("com.android.billingclient:billing:9.1.0", content)
        self.assertNotIn("listenablefuture", content)  # JAR-only module.
        self.assertNotIn("only-debug", content)
        self.assertEqual(0, self.run_tool("--check"))

    def test_stale_versioned_notices_fail_the_check(self):
        self.assertEqual(0, self.run_tool())
        self.artifacts["com.android.billingclient:billing:9.1.0"] = aar({"Protocol Buffers": "updated notice"})
        self.publish()
        self.assertEqual(1, self.run_tool("--check"))
        (self.root / notices.OUTPUT).unlink()
        self.assertEqual(1, self.run_tool("--check"))

    def test_unverified_missing_or_ambiguous_artifacts_are_refused(self):
        self.publish(verified={"com.android.billingclient:billing:9.1.0": "0" * 64})
        self.assertEqual(1, self.run_tool())
        self.publish()
        self.write_lock(list(self.artifacts) + ["com.google.android.gms:play-services-tasks:18.2.0"])
        self.assertEqual(1, self.run_tool())
        self.assertFalse((self.root / notices.OUTPUT).exists())

    def test_raw_terminator_is_refused_instead_of_asserted(self):
        with self.assertRaises(notices.NoticeError):
            notices.dart_literal("text with ''' terminator")


if __name__ == "__main__":
    unittest.main()
